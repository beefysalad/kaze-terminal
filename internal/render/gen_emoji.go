//go:build ignore

// gen_emoji writes emoji_tables.go from Unicode's emoji-data.txt.
//
//	go run gen_emoji.go              (downloads the file)
//	go run gen_emoji.go emoji-data.txt
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"sort"
	"strconv"
	"strings"
)

const (
	version = "15.1.0"
	url     = "https://www.unicode.org/Public/" + version + "/ucd/emoji/emoji-data.txt"
)

type span struct{ lo, hi rune }

func main() {
	var src io.Reader
	if len(os.Args) > 1 {
		f, err := os.Open(os.Args[1])
		if err != nil {
			log.Fatal(err)
		}
		defer f.Close()
		src = f
	} else {
		resp, err := http.Get(url)
		if err != nil {
			log.Fatal(err)
		}
		defer resp.Body.Close()
		src = resp.Body
	}
	pres := map[rune]bool{}
	sc := bufio.NewScanner(src)
	for sc.Scan() {
		line, _, _ := strings.Cut(sc.Text(), "#")
		cps, prop, ok := strings.Cut(line, ";")
		if !ok {
			continue
		}
		var into map[rune]bool
		switch strings.TrimSpace(prop) {
		case "Emoji_Presentation":
			into = pres
		default:
			continue
		}
		a, b, _ := strings.Cut(strings.TrimSpace(cps), "..")
		lo, err := strconv.ParseUint(a, 16, 32)
		if err != nil {
			log.Fatal(err)
		}
		hi := lo
		if b != "" {
			if hi, err = strconv.ParseUint(b, 16, 32); err != nil {
				log.Fatal(err)
			}
		}
		for r := rune(lo); r <= rune(hi); r++ {
			into[r] = true
		}
	}
	if err := sc.Err(); err != nil {
		log.Fatal(err)
	}
	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by gen_emoji.go from %s; DO NOT EDIT.\n\n", url)
	fmt.Fprintf(&out, "package render\n\n")
	write(&out, "emojiPresentationSpans", "Emoji_Presentation=Yes (Unicode "+version+")", pres)
	src2, err := format.Source(out.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("emoji_tables.go", src2, 0o644); err != nil {
		log.Fatal(err)
	}
}

func write(w io.Writer, name, doc string, set map[rune]bool) {
	rs := make([]rune, 0, len(set))
	for r := range set {
		rs = append(rs, r)
	}
	sort.Slice(rs, func(i, j int) bool { return rs[i] < rs[j] })
	var spans []span
	for _, r := range rs {
		if n := len(spans); n > 0 && spans[n-1].hi+1 == r {
			spans[n-1].hi = r
		} else {
			spans = append(spans, span{r, r})
		}
	}
	fmt.Fprintf(w, "// %s: %s.\nvar %s = [...]runeSpan{\n", name, doc, name)
	for _, s := range spans {
		fmt.Fprintf(w, "\t{0x%04X, 0x%04X},\n", s.lo, s.hi)
	}
	fmt.Fprintf(w, "}\n\n")
}
